/// Icon and name for items whose look depends on the damage value.
pub fn variant(id: ItemId, meta: i32) -> Option<(&'static str, &'static str)> {
    let m = meta.clamp(0, 15) as usize;
    Some(match id {
        263 if meta == 1 => ("charcoal", "Charcoal"),
        261 if meta == 1000 => ("bow_pulling_0", "Bow"),
        261 if meta == 1001 => ("bow_pulling_1", "Bow"),
        261 if meta == 1002 => ("bow_pulling_2", "Bow"),
        349 => [
            ("fish_cod_raw", "Raw Fish"),
            ("fish_salmon_raw", "Raw Salmon"),
            ("fish_clownfish_raw", "Clownfish"),
            ("fish_pufferfish_raw", "Pufferfish"),
        ][m.min(3)],
        350 => [
            ("fish_cod_cooked", "Cooked Fish"),
            ("fish_salmon_cooked", "Cooked Salmon"),
        ][m.min(1)],
        351 => DYES[m],
        397 => [
            ("skull_skeleton", "Skeleton Skull"),
            ("skull_wither", "Wither Skeleton Skull"),
            ("skull_zombie", "Zombie Head"),
            ("skull_steve", "Head"),
            ("skull_creeper", "Creeper Head"),
        ][m.min(4)],
        _ => return None,
    })
}

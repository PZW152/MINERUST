use crate::item::ItemId;

pub struct ItemDef {
    pub id: ItemId,
    pub icon: &'static str,
    pub name: &'static str,
    pub stack: u32,
    pub max_damage: i32,
}

const fn d(
    id: ItemId,
    icon: &'static str,
    name: &'static str,
    stack: u32,
    max_damage: i32,
) -> ItemDef {
    ItemDef {
        id,
        icon,
        name,
        stack,
        max_damage,
    }
}

